# Inicia un bucle for que itera i desde 1 hasta 5
for i in range(1, 6):
    # Entra en un bucle while que se ejecuta mientras i sea menor o igual a 4
    while i <= 4:
        # Incrementa el valor de i en 1 en cada iteracion
        i += 1
        # Imprime el valor actualizado de i
        print(i)
    # Interrumpe y finaliza el bucle for de forma inmediata
    break